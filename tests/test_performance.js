const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../core/performance.js'), 'utf8'), context);
assert.equal(context.format(null, '%'), 'N/D');
assert.equal(context.format(NaN, '%'), 'N/D');
assert.equal(context.format(0, '%', 2), '0.00%');
assert.equal(context.duration(1250), '1.25 s');
const a = {id: 'a', context: {fingerprint: 'same'}, startupMs: null, summary: {cpuPercent: .5, rssMiB: 100, pssMiB: null}};
const b = {id: 'b', context: {fingerprint: 'same'}, startupMs: 500, summary: {cpuPercent: .2, rssMiB: 110, pssMiB: 80}};
const result = context.compare(a, b);
assert.ok(result.compatible);
assert.ok(Math.abs(result.cpu + .3) < 1e-9);
assert.equal(result.rss, 10);
assert.equal(result.pss, null);
assert.equal(result.startup, null);
assert.equal(context.compare(a, a).compatible, false);
b.context.fingerprint = 'different';
assert.equal(context.compare(a, b).compatible, false);
