#!/usr/bin/env python3
"""Trace the supplied monochrome artwork and bundle themeable SVGs for QML."""

import json
import math
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets'


def read_mask(path):
  result = subprocess.run(['magick', str(path), '-colorspace', 'Gray', '-threshold', '50%',
    '-trim', '+repage', '-bordercolor', 'black', '-border', '12', '-depth', '8', 'pgm:-'],
    check=True, capture_output=True, timeout=15)
  data = result.stdout
  header = re.match(rb'P5\s+(\d+)\s+(\d+)\s+255\s', data)
  if not header:
    raise ValueError('Se esperaba una máscara PGM de 8 bits')
  width, height = map(int, header.groups())
  pixels = data[header.end():]
  if len(pixels) != width * height:
    raise ValueError('La máscara está incompleta')
  return width, height, pixels


def simplify(points, tolerance=0.75):
  if len(points) < 3:
    return points
  start, end = points[0], points[-1]
  dx, dy = end[0] - start[0], end[1] - start[1]
  length = math.hypot(dx, dy)
  distances = [(abs(dy * (x - start[0]) - dx * (y - start[1])) / length
    if length else math.hypot(x - start[0], y - start[1])) for x, y in points[1:-1]]
  distance = max(distances, default=0)
  if distance <= tolerance:
    return [start, end]
  pivot = distances.index(distance) + 1
  return simplify(points[:pivot + 1], tolerance)[:-1] + simplify(points[pivot:], tolerance)


def contours(width, height, pixels):
  edges = {}

  def add(start, end):
    edges.setdefault(start, set()).add(end)

  for y in range(1, height - 1):
    for x in range(1, width - 1):
      index = y * width + x
      if not pixels[index]:
        continue
      if not pixels[index - width]:
        add((x, y), (x + 1, y))
      if not pixels[index + 1]:
        add((x + 1, y), (x + 1, y + 1))
      if not pixels[index + width]:
        add((x + 1, y + 1), (x, y + 1))
      if not pixels[index - 1]:
        add((x, y + 1), (x, y))

  directions = {(1, 0): 0, (0, 1): 1, (-1, 0): 2, (0, -1): 3}
  while edges:
    first = min(edges)
    point, previous = first, 0
    loop = [point]
    while True:
      choices = edges[point]
      def turn(candidate):
        direction = directions[(candidate[0] - point[0], candidate[1] - point[1])]
        return {1: 0, 0: 1, 3: 2, 2: 3}[(direction - previous) % 4]
      following = min(choices, key=turn)
      choices.remove(following)
      if not choices:
        del edges[point]
      previous = directions[(following[0] - point[0], following[1] - point[1])]
      point = following
      if point == first:
        break
      loop.append(point)
    area = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(loop, loop[1:] + loop[:1])) / 2
    if abs(area) < 6:
      continue
    pivot = max(range(len(loop)), key=lambda index: math.dist(first, loop[index]))
    yield simplify(loop[:pivot + 1])[:-1] + simplify(loop[pivot:] + [first])[:-1]


def trace(source, destination, title):
  width, height, pixels = read_mask(source)
  scale = 128 / max(width, height)
  offset = ((128 - width * scale) / 2, (128 - height * scale) / 2)
  paths = []
  for loop in contours(width, height, pixels):
    coordinates = [f'{x * scale + offset[0]:.3f},{y * scale + offset[1]:.3f}' for x, y in loop]
    paths.append('M' + 'L'.join(coordinates) + 'Z')
  svg = '<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">\n'
  svg += '  <title>' + title + '</title>\n  <path fill="#ffffff" fill-rule="evenodd" d="' + ''.join(paths) + '"/>\n</svg>\n'
  destination.write_text(svg)
  print(f'{destination.relative_to(ROOT)}: {len(paths)} contornos, {len(svg)} bytes')


def bundle():
  artwork = {}
  for name, filename in [('hyprlarp', 'hyprlarp.svg'), ('error', 'error.svg'), ('application', 'application.svg')]:
    svg = (ASSETS / filename).read_text().strip()
    artwork[name] = re.sub(r'(fill|stroke)=([\"\'])(#ffffff|#fff|white)\2',
      lambda match: match[1] + '="@@COLOR@@"', svg, flags=re.IGNORECASE)
  source = '.pragma library\n// Generated by tools/prepare_branding.py from the SVG assets.\n'
  source += 'const artwork = ' + json.dumps(artwork, ensure_ascii=False, indent=2) + ';\n'
  source += '''// Retain only the latest tint per asset; opening another panel reuses its
// URI without accumulating the colors visited in the appearance editor.
const artworkSourceCache = Object.create(null);
function supports(name) {
  return Object.prototype.hasOwnProperty.call(artwork, name);
}
function source(name, color, opacity) {
  if (!supports(name))
    return "";
  const previous = artworkSourceCache[name];
  if (previous && previous.color === color && previous.opacity === opacity)
    return previous.uri;
  const svg = artwork[name].replace(/@@COLOR@@/g, color).replace("<svg ", '<svg opacity="' + opacity + '" ');
  const uri = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(svg);
  artworkSourceCache[name] = {color: color, opacity: opacity, uri: uri};
  return uri;
}
'''
  (ASSETS / 'branding.js').write_text(source)
  # The standalone greeter is its own Quickshell config root.
  (ROOT / 'greeter/branding.js').write_text(source)


def main():
  trace(ASSETS / 'icono-hyprlarp.png', ASSETS / 'hyprlarp.svg', 'HyprLarp')
  trace(ASSETS / 'icono-error.png', ASSETS / 'error.svg', 'Error')
  logo = (ASSETS / 'hyprlarp.svg').read_text()
  path = re.search(r'  <path[^\n]+', logo)[0].strip()
  desktop = '<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">\n'
  desktop += '  <title>HyprLarp</title>\n  <rect width="128" height="128" rx="24" fill="#000000"/>\n'
  desktop += '  <g transform="translate(12 12) scale(0.8125)">' + path + '</g>\n</svg>\n'
  (ASSETS / 'hyprlarp-desktop.svg').write_text(desktop)
  bundle()


if __name__ == '__main__':
  main()
